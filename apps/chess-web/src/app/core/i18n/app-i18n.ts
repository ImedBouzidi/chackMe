export type AppLanguageCode = 'en' | 'ar' | 'fr' | 'es';

export interface AppLanguage {
  code: AppLanguageCode;
  name: string;
  dir: 'ltr' | 'rtl';
  speechLang: string;
}

export const APP_LANGUAGES: AppLanguage[] = [
  { code: 'en', name: 'English', dir: 'ltr', speechLang: 'en-US' },
  { code: 'ar', name: 'العربية', dir: 'rtl', speechLang: 'ar-SA' },
  { code: 'fr', name: 'Français', dir: 'ltr', speechLang: 'fr-FR' },
  { code: 'es', name: 'Español', dir: 'ltr', speechLang: 'es-ES' }
];

export const DEFAULT_LANGUAGE: AppLanguageCode = 'en';

export function isAppLanguageCode(value: string | null | undefined): value is AppLanguageCode {
  return value === 'en' || value === 'ar' || value === 'fr' || value === 'es';
}

export function languageDirection(code: AppLanguageCode): 'ltr' | 'rtl' {
  return code === 'ar' ? 'rtl' : 'ltr';
}

